export type TK = keyof typeof C;
export function tc(k: TK, lang: Lang, v?: Record<string, string | number>): string {
  let s: string = C[k][lang];
  if (v) for (const key of Object.keys(v)) s = s.split(`{${key}}`).join(String(v[key]));
  return s;
}

